for (const [path, replacements] of Object.entries(replacementsByFile)) {
  let content = fs.readFileSync(path, 'utf8');
  let changed = false;
  for (const [from, to] of replacements) {
    if (content.includes(from)) {
      content = content.split(from).join(to);
      changed = true;
    }
  }
  if (changed) {
    fs.writeFileSync(path, content, 'utf8');
    console.log(`[retire-machinery-v2] cleaned fallback machinery motifs in ${path}`);
  }
}

// Guard only against the specific fallback motifs Merry never wants generated by default.
// This does NOT block a literal user prompt from mentioning a machine when they explicitly ask for one.
const runtimeChecks = [
  ['lib/david.ts', /bronze gears|calibrated clockwork|clockwork mechanisms|Mechanical timepiece/i],
  ['src/utils/recipeStorage.ts', /submerged gear train|mechanical bronze cathedral/i],
];

const failures = [];
for (const [path, pattern] of runtimeChecks) {
  const content = fs.readFileSync(path, 'utf8');
  if (pattern.test(content)) failures.push(`${path}: retired machinery fallback still present`);
}

if (failures.length) {
  console.error('\n[retire-machinery-v2] FAILED');
  failures.forEach((failure) => console.error(' - ' + failure));
  process.exit(1);
}

